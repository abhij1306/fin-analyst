def category(table: str, column: str) -> str | None:
    """ "masked", "mask store" or "as filed"; None for a column this registry does not list."""
    for name, columns in (("masked", MASKED), ("mask store", MASK_STORE), ("as filed", AS_FILED)):
        if column in columns.get(table, ()):
            return name
    return None
